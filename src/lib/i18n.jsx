const LANG_STORAGE_KEY = 'bidzo_lang';
const SUPPORTED_LANGS = ['lv', 'en', 'ru'];

function getInitialLang() {
  if (typeof window === 'undefined') return 'lv';
  try {
    const stored = window.localStorage.getItem(LANG_STORAGE_KEY);
    if (stored && SUPPORTED_LANGS.includes(stored)) return stored;
  } catch (e) {
    // localStorage unavailable (private mode etc.) -- fall through to default
  }
  return 'lv';
}

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(getInitialLang);

  const setLang = (next) => {
    if (!SUPPORTED_LANGS.includes(next)) return;
    setLangState(next);
    try {
      window.localStorage.setItem(LANG_STORAGE_KEY, next);
    } catch (e) {
      // ignore -- language just won't persist across reloads
    }
  };

  const t = (path) => {
    const keys = path.split('.');
    let result = translations[lang];
    for (const key of keys) {
      result = result?.[key];
    }
    // Only fall back to the raw path for genuinely missing keys -- `||` would
    // also treat legitimate falsy values (e.g. an intentionally empty string
    // like page_privacy.disclaimer for lv) as missing and leak the path
    // itself into the UI.
    return result !== undefined ? result : path;
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
